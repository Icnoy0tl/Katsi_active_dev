# Numerical constants
EPS_TIE = 1e-9      # two affinities closer than this are considered TIED
EPS_FLOOR = 1e-6    # minimum target effective_n over the number of tied items at the max
BETA_MAX = 1e12     # search cap for beta (if reached: converged=False)


# --------------------------------------------------------------------------
# BASIC STATISTICAL TOOLS
# --------------------------------------------------------------------------
def entropy(p):
    """
    Shannon entropy H(p) = -sum p_i ln p_i     (convention 0*ln0 = 0).

    Meaning: how much uncertainty / dispersion the distribution p has.
      p = [1, 0, 0, 0]       -> H = 0          (all in one point)
      p = [.25,.25,.25,.25]  -> H = ln 4=1.386 (maximum: even distribution)
    Bound: 0 <= H(p) <= ln(len(p)).
    """
    return -sum(x * math.log(x) for x in p if x > 0)


def effective_n(p):
    """
    Effective number of elements N_ef = exp(H(p))   (a.k.a. perplexity / Hill number).

    Intuition: "p behaves as if it distributed the weight evenly among N_ef elements".
      [.5,.5,0,0]        -> effective_n = 2
      [1,0,0,0]          -> effective_n = 1
      [.25,.25,.25,.25]  -> effective_n = 4
    """
    return math.exp(entropy(p))


def softmax(r, beta):
    """
    w_j = exp(beta*r_j) / sum_i exp(beta*r_i)

    It is the maximum entropy solution (see derivation in README / response).
    beta = "inverse temperature": beta=0 -> all equal; large beta -> highest r wins.

    NUMERICAL STABILITY (log-sum-exp trick): max(r) is subtracted before exponentiating.
    It is algebraically identical (the factor exp(-beta*rmax) cancels out top and bottom),
    but avoids overflow: the largest exponent becomes 0, so exp(...) <= 1 always.
    Example: beta=1000, r=0.35 -> exp(350) overflows; with the trick, exp(0)=1.
    """
    m = max(r)
    e = [math.exp(beta * (x - m)) for x in r]
    s = sum(e)           # s >= 1 because the max term equals exactly 1
    return [x / s for x in e]


# --------------------------------------------------------------------------
# VALIDATION (catches cases where logic previously broke silently)
# --------------------------------------------------------------------------
def _validate(variable_types, profile, cats):
    if len(set(cats)) != len(cats) or not cats:
        raise ValueError("CATEGORIES empty or with duplicates")
    if not variable_types:
        raise ValueError("VARIABLE_TYPES has no variables")
    ok = set(cats)
    for v, row in variable_types.items():
        _validate_vector(row, ok, f"VARIABLE_TYPES['{v}']", sums_one=True)
    _validate_vector(profile, ok, "mission profile", sums_one=False)


def _validate_vector(vec, cats_ok, name, sums_one):
    # A misspelled key ("GEOO") was previously IGNORED silently -> erroneous result.
    bad = set(vec) - cats_ok
    if bad:
        raise ValueError(f"{name}: unknown categories {sorted(bad)}")
    for c, x in vec.items():
        if not (isinstance(x, (int, float)) and math.isfinite(x) and x >= 0):
            raise ValueError(f"{name}[{c}]={x!r}: must be finite and >= 0")
    s = sum(vec.values())
    if sums_one and abs(s - 1) > 1e-9:
        raise ValueError(f"{name}: sum {s}, must sum to 1")
    if not sums_one and s <= 0:
        raise ValueError(f"{name}: sum is 0, the mission demands nothing")


# --------------------------------------------------------------------------
# F3: CALIBRATE beta  (calculus + numerical analysis)
# --------------------------------------------------------------------------
def calibrate_beta(r, target):
    """
    Finds beta >= 0 such that effective_n(softmax(beta*r)) = target.

    Why it exists and is unique (g(beta) := effective_n(w(beta))):
      * g is continuous.
      * g(0) = n                       (even weights)
      * g(+inf) = n_top                (n_top = how many variables tie at the maximum of r)
      * g is STRICTLY decreasing if r is not constant, because
            ln w_j = beta*r_j - ln Z   ->   H(beta) = -beta*E[r] + ln Z
            dH/dbeta = -E[r] - beta*dE[r]/dbeta + E[r] = -beta * Var_w(r)  < 0   (beta>0)
        (using dlnZ/dbeta = E_w[r]  and  dE_w[r]/dbeta = Var_w(r)).
      => by the Intermediate Value Theorem + strict monotonicity, for every
         target in (n_top, n) there is exactly ONE beta. Found via bisection
         (each step halves the interval: error <= hi/2^k).

    Limit cases resolved here (returns beta=0, "nothing to concentrate"):
      * target >= n         (profile asking for everything equally)
      * all r tied (n_top = n, e.g., mission with no aligned variables)
      * n = 1
    Returns (beta, converged, used_target) -- used_target = target after floor.
    """
    n = len(r)
    rmax = max(r)
    n_top = sum(1 for x in r if rmax - x <= EPS_TIE)
    # effective_n never drops below n_top (reached only in the limit beta->inf): floor.
    target = max(target, n_top + EPS_FLOOR)
    if target >= n:
        return 0.0, True, float(n)

    g = lambda b: effective_n(softmax(r, b))

    # Enclose the root: g(0)=n > target; we search hi with g(hi) <= target.
    hi = 1.0
    while g(hi) > target:
        hi *= 2.0
        if hi > BETA_MAX:        # almost exact ties: could not enclose
            return hi, False, target
    lo = 0.0
    for _ in range(200):          # bisection: invariant g(lo) > target >= g(hi)
        mid = 0.5 * (lo + hi)
        if g(mid) > target:
            lo = mid
        else:
            hi = mid
    return 0.5 * (lo + hi), True, target


# --------------------------------------------------------------------------
# F1 + F2 + F3 combined
# --------------------------------------------------------------------------
def factors(profile, variable_types=VARIABLE_TYPES, cats=CATEGORIES):
    """
    Returns dict with beta, effective_n, target_n, angle_deg, flags and, per variable:
        affinity r_j, factor f_j (mean 1), weight w_j (sum 1).

    Example (mission 'rover', n=25 variables, C=7 categories):
        r['grain_size_um']  = 1.0*0.35           = 0.350   (pure MEC type; rover demands MEC .35)
        r['soil_moisture']  = .5*.35 + .5*.20    = 0.275
        r['wind_gust_ms']   = 1.0*0.0            = 0.000   (rover does not demand ATM)
        N*  = 24*exp(H(d))/7 = 14.34  ->  beta = 11.0
        factor f = n*w:  grain 2.84 (goes up), soil_moisture 1.25 (goes up), wind_gust 0.06 (goes down)
    """
    _validate(variable_types, profile, cats)
    variables = list(variable_types)
    n = len(variables)

    # --- "Used" categories: those touched by at least one variable. A category
    # that no variable covers cannot influence; without this filter, adding an
    # empty category would change N* (and the weights) without physics changing.
    used = [c for c in cats if sum(variable_types[v].get(c, 0.0) for v in variables) > 0]
    C = len(used)

    # --- Profile restricted to used categories and renormalized (sums to 1).
    mass = sum(profile.get(c, 0.0) for c in used)
    if mass <= 0:
        # The mission only demands categories that no variable covers:
        # no information to prioritize -> even weights (nothing is invented).
        w = [1.0 / n] * n
        return _package(variables, [0.0] * n, w, 0.0, float(n), float(n),
                        converged=True, no_affinity=True)
    d = {c: profile.get(c, 0.0) / mass for c in used}

    # --- F1: affinity r_j = sum_c variable_types[j,c]*d[c]  (dot product)
    # Probability: r_j = P(variable category == category demanded by the mission)
    #   if c ~ variable_types_j and c' ~ d are drawn independently. Always in [0, 1].
    r = [sum(variable_types[v].get(c, 0.0) * d[c] for c in used) for v in variables]

    # --- F3: N* = n * exp(H(d)) / C
    # "The mission distributes its demand among exp(H(d)) of the C categories; the weights
    #  must be distributed among the same FRACTION of the n variables."
    #   uniform d   -> exp(H)=C  -> N*=n   (everything matters equally, beta=0)
    #   d in 1 only -> exp(H)=1  -> N*=n/C (only ~n/C variables matter)
    n_obj = n * effective_n(list(d.values())) / C
    beta, ok, n_used = calibrate_beta(r, n_obj)
    # n_obj can be UNREACHABLE (< n_top): e.g., n=3 variables, C=12 categories, profile
    # one-hot -> N* = 0.25 < 1. No softmax can have effective_n < n_top, so the
    # floor n_top + EPS_FLOOR is used. Reported in 'floor_applied' so it doesn't pass silently.
    floor = n_used > n_obj + 1e-12 and n_used < n

    # --- F2: weights and factor
    w = softmax(r, beta)
    all_tied = (max(r) - min(r)) <= EPS_TIE
    return _package(variables, r, w, beta, n_used, effective_n(w), ok, all_tied,
                    theoretical_n=n_obj, floor=floor)


def _package(variables, r, w, beta, n_obj, n_ef, converged, no_affinity,
             theoretical_n=None, floor=False):
    n = len(variables)
    # Hellinger angle with respect to the even distribution (trigonometry):
    #   vectors (sqrt(w_j)) have norm 1 (sum w = 1) => live on the unit sphere.
    #   Even distribution is u = (1/sqrt n, ..., 1/sqrt n). cos(theta) = sum sqrt(w_j/n).
    #   theta = 0 degrees -> even weights; larger theta -> more concentrated.
    cos_t = min(1.0, sum(math.sqrt(x / n) for x in w))
    return {
        "beta": beta,
        "effective_n": n_ef,
        "target_n": n_obj,                         # actually used
        "theoretical_target_n": n_obj if theoretical_n is None else theoretical_n,  # N* unclipped
        "floor_applied": floor,
        "angle_deg": math.degrees(math.acos(cos_t)),
        "converged": converged,
        "no_affinity": no_affinity,
        "variables": {
            v: {"affinity": r[i], "factor": n * w[i], "weight": w[i]}
            for i, v in enumerate(variables)
        },
    }


