"""
WEIGHT ADJUSTMENT FACTOR BY VARIABLE TYPE AND MISSION TYPE
================================================================
Does not use region values: only (a) the TYPE of each variable and
(b) the demand PROFILE of the mission.

Concept map (which branch of mathematics each step comes from)
------------------------------------------------------------------
  F1  r_j  = mu_j . d            LINEAR ALGEBRA / PROBABILITY  (dot product, cosine)
  F2  w_j  = softmax(beta * r)   CONSTRAINED OPTIMIZATION (Lagrange multipliers),
                                 INFORMATION THEORY (maximum entropy / minimum KL)
  F3  beta : H(w) = H target     CALCULUS (derivative, monotonicity, intermediate value theorem)
                                 + NUMERICAL ANALYSIS (bisection)

Geometry in one image (C = 2 categories, GEO-MEC plane):

        MEC ^
            |      d (mission profile)
            |     /
            |    /  theta_2
        mu_2 *--/-----          r_j = mu_j . d = |mu_j| |d| cos(theta_j)
            |  /                small theta -> variable aligned with mission -> high r
            | / theta_1         theta = 90 degrees -> orthogonal variable -> r = 0
            |/____________*mu_1 ----> GEO

See also figure 'geometries_weights.png' (generated by figures.py).
"""

